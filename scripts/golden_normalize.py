#!/usr/bin/env python3
"""Normalize a generated Sokrates output tree in place so two runs of the same code compare equal:
drops timing/log/image files, re-serializes JSON with sorted keys and without volatile fields,
replaces dates/times/durations in text and HTML. Used by scripts/golden.sh."""
import json
import os
import re
import sys

DROP_FILES = {"executionTimes.txt", "executionTimes.json", "executionStats.json", "analysisStats.json"}
DROP_SUFFIXES = (".log", ".png", ".jpg", ".jpeg", ".gif", ".ico", ".zip")
VOLATILE_KEYS = {"analysisStartTimeMs", "analysisEndTimeMs", "timestamp", "durationMs", "executionTimeMs", "analysisDate",
                 "TOTAL_ANALYSIS_TIME_IN_MILLIS"}
VOLATILE_LINE = re.compile(r"TOTAL_ANALYSIS_TIME_IN_MILLIS|Total analysis time|Executed '|generated on|Generated by Sokrates on", re.I)
DATE = re.compile(r"\d{4}-\d{2}-\d{2}( \d{2}:\d{2}(:\d{2})?)?")
DURATION = re.compile(r"\b\d+(\.\d+)? ?(ms|millis|milliseconds)\b")
TEXT_EXT = (".txt", ".csv", ".md", ".html", ".htm", ".js", ".svg", ".mmd", ".dot", ".css")


def scrub(obj):
    if isinstance(obj, dict):
        if obj.get("id") == "TOTAL_ANALYSIS_TIME_IN_MILLIS":  # a metric entry: keep it, drop its value
            obj = dict(obj, value=0)
        return {k: scrub(v) for k, v in obj.items() if k not in VOLATILE_KEYS and not k.endswith("TimeInMillis")}
    if isinstance(obj, list):
        return [scrub(v) for v in obj]
    if isinstance(obj, str):
        return DATE.sub("DATE", obj)
    return obj


def normalize_text(text):
    lines = [l for l in text.splitlines() if not VOLATILE_LINE.search(l)]
    text = "\n".join(lines)
    text = DATE.sub("DATE", text)
    text = DURATION.sub("N ms", text)
    return text + "\n"


def main(root):
    for dirpath, _, files in os.walk(root):
        for name in files:
            path = os.path.join(dirpath, name)
            if name in DROP_FILES or name.endswith(DROP_SUFFIXES):
                os.remove(path)
                continue
            if name.endswith(".json"):
                try:
                    with open(path, encoding="utf-8") as f:
                        data = json.load(f)
                    with open(path, "w", encoding="utf-8") as f:
                        json.dump(scrub(data), f, indent=1, sort_keys=True, ensure_ascii=False)
                    continue
                except (ValueError, UnicodeDecodeError):
                    pass
            if name.endswith(TEXT_EXT) or name.endswith(".json"):
                try:
                    with open(path, encoding="utf-8") as f:
                        text = f.read()
                except UnicodeDecodeError:
                    continue
                with open(path, "w", encoding="utf-8") as f:
                    f.write(normalize_text(text))


if __name__ == "__main__":
    main(sys.argv[1])
