package nl.obren.sokrates.sourcecode.scoping;

import nl.obren.sokrates.sourcecode.SourceFile;
import org.junit.jupiter.api.Test;

import java.io.File;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Acceptance test of task t03: the default scoping conventions that could never match now classify
 * the files they are meant for (generated .htm pages, .NET XML documentation files, *-gradle.js
 * build scripts), while the files they already matched keep matching and ordinary source files
 * stay out of those scopes.
 */
public class ScopingConventionsNeverMatchedTest {
    private final ScopingConventions conventions = new ScopingConventions();

    @Test
    public void pkgdownHtmPageIsGenerated() {
        assertMatches(conventions.getGeneratedFilesConventions(), "/repo/reference/index.htm",
                "<!DOCTYPE html><!-- Generated by pkgdown: do not edit by hand -->", "<html lang=\"en\">");
    }

    @Test
    public void doxygenHtmPageIsGenerated() {
        assertMatches(conventions.getGeneratedFilesConventions(), "/repo/api/classFoo.htm",
                "<!DOCTYPE html PUBLIC \"-//W3C//DTD XHTML 1.0 Transitional//EN\">", "<html>", "<head>",
                "<title>My Project: Generated by Doxygen 1.9.1</title>");
    }

    @Test
    public void htmPageWithAGeneratorMetaTagIsGenerated() {
        assertMatches(conventions.getGeneratedFilesConventions(), "/repo/www/page.htm",
                "<html>", "<head>", "  <meta name=\"generator\" content=\"Hugo 0.80\">");
    }

    @Test
    public void dotNetXmlDocumentationFileIsGenerated() {
        assertMatches(conventions.getGeneratedFilesConventions(), "/repo/bin/Release/MyAssembly.xml",
                "<?xml version=\"1.0\"?>", "<doc>", "  <assembly>");
    }

    @Test
    public void gradleJsScriptIsABuildAndDeploymentFile() {
        assertMatches(conventions.getBuildAndDeploymentFilesConventions(), "/repo/tools/build-gradle.js");
    }

    @Test
    public void whatAlreadyMatchedKeepsMatching() {
        List<Convention> generated = conventions.getGeneratedFilesConventions();
        assertMatches(generated, "/repo/api/classFoo.html",
                "<!DOCTYPE html>", "<html>", "<title>My Project: Generated by Doxygen 1.9.1</title>");
        assertMatches(generated, "/repo/www/page.xhtml", "<html>", "<head>", "  <meta name=\"generator\" content=\"Hugo 0.80\">");
        assertMatches(generated, "/repo/app/main.js", "// Generated by CoffeeScript 1.12.7", "(function() {");
        assertMatches(conventions.getBuildAndDeploymentFilesConventions(), "/repo/build.gradle");
    }

    @Test
    public void ordinaryFilesStayOutOfThoseScopes() {
        List<Convention> generated = conventions.getGeneratedFilesConventions();
        assertNotMatches(generated, "/repo/www/about.htm", "<html>", "<body>Hello</body>", "</html>");
        assertNotMatches(generated, "/repo/app/main.js", "'use strict';", "module.exports = {};");
        assertNotMatches(generated, "/repo/config/settings.xml", "<?xml version=\"1.0\"?>", "<settings>", "</settings>");
        assertNotMatches(conventions.getBuildAndDeploymentFilesConventions(), "/repo/app/gradle-view.js");
    }

    private void assertMatches(List<Convention> conventions, String path, String... lines) {
        assertTrue(matchesAny(conventions, path, lines), "expected a convention to match " + path);
    }

    private void assertNotMatches(List<Convention> conventions, String path, String... lines) {
        assertFalse(matchesAny(conventions, path, lines), "expected no convention to match " + path);
    }

    private boolean matchesAny(List<Convention> conventions, String path, String... lines) {
        SourceFile sourceFile = new SourceFile(new File(path), String.join("\n", lines));
        return conventions.stream().anyMatch(convention -> convention.matches(sourceFile));
    }
}
