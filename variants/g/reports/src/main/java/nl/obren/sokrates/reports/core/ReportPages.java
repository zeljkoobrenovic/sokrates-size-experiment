package nl.obren.sokrates.reports.core;

/**
 * The catalogue of the HTML report pages of a single-repository report (the pages in the {@code html} folder,
 * linked from {@code index.html}).
 * <p>
 * Each page has a file name, a page title (the heading of the page itself), a menu title (the label of the page in
 * the index-page menu, see {@code ReportFileExporter.getReportsList}; it differs for some pages) and an icon key
 * (a file in {@code /icons/<key>.svg}).
 * <p>
 * Used by: {@code BasicSourceCodeReportGenerator} (creates the pages), {@code ReportFileExporter} (index-page menu,
 * info blocks and "Visuals" tab links), {@code SummaryUtils} (summary links) and
 * {@code LandscapeRepositoriesReport} (links from the landscape repository tables to the repository pages).
 * <p>
 * Also linked from: the {@code templates/Structure.html} template and a few in-text links in the page generators
 * (for example {@code MetricsListReportGenerator}, {@code ControlsReportGenerator}), which keep their literal file
 * names.
 */
public enum ReportPages {
    /** Source code overview: volume, size, lines of code, main / test / other code, scope, extensions. */
    SOURCE_CODE_OVERVIEW("SourceCodeOverview.html", "Source Code Overview", "Source Code Overview", "codebase"),
    /** Components: logical decomposition, modules, code organization (generated by {@code LogicalComponentsReportGenerator}). */
    COMPONENTS("Components.html", "Components", "Components", "code_organization"),
    /** Component dependencies: static dependencies, logical decomposition with dependencies, coupling between components. */
    COMPONENT_DEPENDENCIES("ComponentsAndDependencies.html", "Static Component Dependencies", "Component Dependencies*", "dependencies"),
    /** Temporal dependencies: files changed together, co-change, temporal coupling (generated by {@code FileTemporalDependenciesReportGenerator}). */
    TEMPORAL_DEPENDENCIES("FileTemporalDependencies.html", "Temporal Dependencies", "Temporal Dependencies", "temporal_dependency"),
    /** Duplication: duplicated code, copy-paste, clones (generated by {@code DuplicationReportGenerator}). */
    DUPLICATION("Duplication.html", "Duplication", "Duplication", "duplication"),
    /** File size: large files, long files, lines of code per file (generated by {@code FileSizeReportGenerator}). */
    FILE_SIZE("FileSize.html", "File Size", "File Size", "file_size"),
    /** File age and freshness: file history, last modified, first modified, stale files (generated by {@code FileAgeReportGenerator}). */
    FILE_AGE("FileAge.html", "File Age & Freshness", "File Age & Freshness", "file_history"),
    /** File change frequency: churn, hot spots, how often files change (generated by {@code FileChurnReportGenerator}). */
    FILE_CHANGE_FREQUENCY("FileChangeFrequency.html", "File Change Frequency", "File Change Frequency", "change"),
    /** Commits: git history, activity, commit trends (generated by {@code CommitsReportGenerator}). */
    COMMITS("Commits.html", "Commits", "Commits", "commits"),
    /** Contributors: authors, committers, developers, people (generated by {@code ContributorsReportGenerator}). */
    CONTRIBUTORS("Contributors.html", "Contributors", "Contributors", "contributors"),
    /** Unit size: long methods, functions, procedures (generated by {@code UnitsSizeReportGenerator}). */
    UNIT_SIZE("UnitSize.html", "Unit Size", "Unit Size*", "unit_size"),
    /** Conditional complexity: cyclomatic complexity, McCabe index (generated by {@code ConditionalComplexityReportGenerator}). */
    CONDITIONAL_COMPLEXITY("ConditionalComplexity.html", "Conditional Complexity", "Conditional Complexity*", "conditional"),
    /** Features of interest: concerns, cross-cutting concerns, tags, search patterns (generated by {@code ConcernsReportGenerator}). */
    FEATURES_OF_INTEREST("FeaturesOfInterest.html", "Features of Interest", "Features of Interest", "cross_cutting_concerns"),
    /** Metrics: the list of all metrics (generated by {@code MetricsListReportGenerator}). */
    METRICS("Metrics.html", "Metrics", "All Metrics", "metrics"),
    /** Trend: comparison with earlier analyses, history of metrics (generated by {@code TrendReportGenerator}). */
    TREND("Trend.html", "Trend", "Trend", "trend"),
    /** Goals and controls: thresholds, alarms, traffic lights (generated by {@code ControlsReportGenerator}). */
    CONTROLS("Controls.html", "Goals & Controls", "Goals & Controls", "goal"),
    /** Notes and findings: user-written findings (generated by {@code FindingsReportGenerator}). */
    NOTES("Notes.html", "Notes & Findings", "Notes & Findings", "notes");

    private final String fileName;
    private final String title;
    private final String menuTitle;
    private final String icon;

    ReportPages(String fileName, String title, String menuTitle, String icon) {
        this.fileName = fileName;
        this.title = title;
        this.menuTitle = menuTitle;
        this.icon = icon;
    }

    public String getFileName() {
        return fileName;
    }

    public String getTitle() {
        return title;
    }

    public String getMenuTitle() {
        return menuTitle;
    }

    public String getIcon() {
        return icon;
    }

    /**
     * @return a new, empty report for this page, with the page title and the file name
     */
    public RichTextReport newReport() {
        return new RichTextReport(title, fileName);
    }
}
